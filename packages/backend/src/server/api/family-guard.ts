/**
 * Sub-account family guard declarations.
 *
 * A sub-account (users.parentUserId != null) must not be able to lock out or
 * wreck its parent or sibling sub-accounts through admin/moderator operations.
 * Each privileged endpoint declares how that is checked (see FamilyGuardService).
 * This is separate from `secure` (which limits an endpoint to the native token).
 */

export type FamilyTargetSpec = {
	/** request parameter that holds the target user id */
	readonly param: string;
	/** the parameter is an array of user ids */
	readonly array?: boolean;
	/** the parameter is a resource id; the family check is made against the resource owner */
	readonly resolve?: 'note' | 'file' | 'flash' | 'galleryPost' | 'channel' | 'invite';
	/** also refuse when the actor targets itself (sub-accounts cannot do this to themselves) */
	readonly denySelf?: boolean;
};

export type FamilyGuard =
	/** The endpoint cannot target a family member in a harmful way. `reason` is mandatory. */
	| { readonly kind: 'notApplicable'; readonly reason: string }
	/** Dangerous and has no target to check: always refused for sub-accounts. */
	| { readonly kind: 'subDenied' }
	/** Refused when any target is the parent or a sibling (all targets are checked). */
	| { readonly kind: 'targets'; readonly targets: readonly FamilyTargetSpec[] }
	/** Endpoint-specific rule implemented by FamilyGuardService. */
	| { readonly kind: 'rule'; readonly rule: 'role-definition' | 'server-settings' };

export const familyGuard = {
	notApplicable: (reason: string): FamilyGuard => ({ kind: 'notApplicable', reason }),
	subDenied: { kind: 'subDenied' } as FamilyGuard,
	targets: (...targets: FamilyTargetSpec[]): FamilyGuard => ({ kind: 'targets', targets }),
	rule: (rule: 'role-definition' | 'server-settings'): FamilyGuard => ({ kind: 'rule', rule }),
};

