// Storybook shim for frontend-shared/js/locale.ts — serves the locale inlined
// by build-storybook-pre (.storybook/locale.ts) instead of the original
// top-level `await window.fetch('/assets/locales/...')`. That top-level await
// makes rolldown emit invalid chunk code for the static Storybook build
// (a non-async module wrapper that still contains `await`), breaking every
// story at runtime with "SyntaxError: Unexpected reserved word".
// Keep in sync with frontend-shared/js/locale.ts.

import type { Locale } from 'i18n';
// generated by .storybook/preload-locale.js (build-storybook-pre)
// eslint-disable-next-line import/no-default-export
import jaJP from '../locale.js';

export let locale: Locale = jaJP as Locale;

export function updateLocale(newLocale: Locale): void {
	locale = newLocale;
}
